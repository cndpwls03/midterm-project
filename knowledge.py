def topic_text(topic: str) -> str:
    """AI에게 넘겨줄 '제도 자료' 글 (기준일 포함)"""
    t = TOPICS[topic]
    lines = [f"[제도 자료 — 기준일 {BASE_DATE}, 주제: {topic}]"]
    for c in t["concepts"]:
        lines.append(f"- {c['name']}: {c['one_line']}")
        lines += [f"    · {p}" for p in c["points"]]
        lines.append(f"    · 이런 사람에게: {c['for_whom']} / 주의: {c['caution']}")
    lines.append("공식 확인처: " + ", ".join(t["sources"]))
    return "\n".join(lines)


def find_concept(text: str, topic: str = None):
    """
    질문 글에 나온 제도 이름(키워드)으로 개념을 찾는다.
    여러 개가 나오면 질문에서 가장 먼저 나온 것을 고르고, 같은 위치면 지금 상담 주제의 개념을 우선한다.
    예) "IRP랑 연금저축 차이가 뭐야?" → IRP
    """
    best = None   # (나온 위치, 지금 주제가 아니면 1, 개념)
    low = text.lower()
    for t, info in TOPICS.items():
        for c in info["concepts"]:
            for k in c["keys"]:
                pos = low.find(k.lower())
                if pos != -1:
                    cand = (pos, 0 if t == topic else 1, c)
                    if best is None or cand[:2] < best[:2]:
                        best = cand
    return best[2] if best else None


def all_text() -> str:
    """모든 주제의 제도 자료 (AI가 쓴 숫자를 검증할 때 사용)"""
    return "\n".join(topic_text(t) for t in TOPICS)


def concept_by_name(name: str):
    for t in TOPICS.values():
        for c in t["concepts"]:
            if c["name"] == name:
                return c
    return None
